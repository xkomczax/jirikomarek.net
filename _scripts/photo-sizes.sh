#!/bin/sh
# Records the width and height of every gallery photo in _data/photo-sizes.yml.
# The gallery grid uses these to give each photo its real shape before it loads.
# Run it after adding or replacing photos:  sh _scripts/photo-sizes.sh
# Needs macOS (uses the built-in `sips` tool).

cd "$(dirname "$0")/.." || exit 1
out=_data/photo-sizes.yml

find img -mindepth 2 -maxdepth 2 -type f \
  \( -iname '*.webp' -o -iname '*.jpg' -o -iname '*.jpeg' \) \
  -not -path 'img/thumbnails/*' -not -path 'img/previews/*' \
  | sort \
  | xargs sips -g pixelWidth -g pixelHeight 2>/dev/null \
  | awk '
      BEGIN { print "# Generated by _scripts/photo-sizes.sh. Do not edit by hand." }
      /^[^ ]/ { n = $0; sub(/.*\//, "", n); sub(/\.[^.]*$/, "", n) }
      /pixelWidth/  { w = $2 }
      /pixelHeight/ { print n ": [" w ", " $2 "]" }
    ' > "$out"

echo "Wrote $(($(wc -l < "$out") - 1)) photo sizes to $out"
